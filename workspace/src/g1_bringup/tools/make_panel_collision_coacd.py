#!/usr/bin/env python3
"""Give the BSH panel a collision shape a hand can actually get its fingers into.

MuJoCo collides every mesh as its convex hull. The panel is a thin-walled moulding -- a frame
with windows, a round boss and a flanged edge -- and its single shell hull (make_panel_collision.py)
is a solid block over all of it: to the simulator there is no inside, so fingers meant to pinch
a wall are pushed off the part, and the part is shoved around instead of grasped. This replaces
it with an approximate convex decomposition (CoACD), dozens of hulls that follow the walls,
leave the windows and the space under the edge flange open, and keep the clips separate.

    pip install coacd trimesh          # once
    make_panel_collision_coacd.py --stl /path/to/BSH_panel.stl [--hulls 64] [--threshold 0.03]
                                  [--preprocess-resolution 250]

--preprocess-resolution matters most for this part. The STL is not watertight, so CoACD first
remeshes it on a voxel grid of this many cells across its longest side: the default 50 is
1.2 cm voxels on a 0.6 m panel, which thickens its 3 mm walls into slabs and fills the windows'
edges, the boss recess and the space under the top skin. 250 (about 2.4 mm) keeps them: the
top surface then matches the mesh to ~1.4 mm instead of ~4.7 mm.

Rewrites, in g1_conveyor_scene.xml: the generated <mesh> block inside <asset> (part_col_0 ..
part_col_N-1, inline vertices in the PANEL BODY frame, i.e. STL minus the mesh refpos), and in
every body that carries the panel's collision, the generated geom block between its own
markers. Deterministic for a given STL and settings (CoACD seed 0).
"""

import argparse
import pathlib
import re
import sys

import numpy as np

MESH_BEGIN = "<!-- BEGIN generated by tools/make_panel_collision.py -- do not edit by hand -->"
MESH_END = "<!-- END generated by tools/make_panel_collision.py -->"
GEOM_BEGIN = "<!-- BEGIN panel collision geoms (tools/make_panel_collision_coacd.py) -->"
GEOM_END = "<!-- END panel collision geoms -->"
REFPOS = np.array([0.0, 0.001, -0.046])  # must match <mesh name="part_mesh" refpos=...>
GEOM_ATTRS = 'group="3" type="mesh" density="0" rgba="0.9 0.4 0.3 0.4" contype="1" conaffinity="1" friction="1 0.01 0.0001"'


def mesh_line(name, verts):
    flat = " ".join((f"{v:.5f}".rstrip("0").rstrip(".") or "0") for v in verts.ravel())
    return f'    <mesh name="{name}" vertex="{flat}"/>'


def decompose(stl, hulls, threshold, prep_res=50):
    import coacd
    import trimesh

    m = trimesh.load(stl, force="mesh")
    m.vertices = m.vertices - REFPOS
    coacd.set_log_level("error")
    parts = coacd.run_coacd(coacd.Mesh(m.vertices, m.faces), threshold=threshold, max_convex_hull=hulls,
                            preprocess_mode="auto", preprocess_resolution=prep_res, resolution=2000, seed=0)
    out = []
    for v, f in parts:
        h = trimesh.Trimesh(v, f).convex_hull
        out.append(np.asarray(h.vertices))
    return out


def rewrite(scene, hull_verts):
    text = scene.read_text()
    n = len(hull_verts)
    mesh_block = "\n".join(
        [f"    {MESH_BEGIN}",
         f"    <!-- The BSH panel's collision: {n} convex hulls from an approximate convex decomposition "
         "(CoACD) of BSH_panel.stl, in the panel body frame. Regenerate with "
         "make_panel_collision_coacd.py --stl BSH_panel.stl. -->"]
        + [mesh_line(f"part_col_{i}", v) for i, v in enumerate(hull_verts)]
        + [f"    {MESH_END}"])
    a, b = text.index(f"    {MESH_BEGIN}"), text.index(MESH_END) + len(MESH_END)
    text = text[:a] + mesh_block + text[b:]

    geoms = "\n".join([f"      {GEOM_BEGIN}"]
                      + [f'      <geom {GEOM_ATTRS} mesh="part_col_{i}"/>' for i in range(n)]
                      + [f"      {GEOM_END}"])
    # Bodies still on the old three hulls: replace those three geoms.
    old = re.compile(
        r'      <geom group="3" type="mesh" mesh="part_col_shell"[^>]*/>\n'
        r'(?:      <geom group="3" type="mesh" mesh="part_col_clip_\d+"[^>]*/>\n)+')
    text, n_old = old.subn(geoms + "\n", text)
    # Bodies already generated: refresh their block.
    gen = re.compile(re.escape(f"      {GEOM_BEGIN}") + r".*?" + re.escape(f"      {GEOM_END}"), re.S)
    text, n_gen = gen.subn(lambda _: geoms, text)
    scene.write_text(text)
    return n_old + n_gen


def main(argv=None):
    here = pathlib.Path(__file__).resolve().parent
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--stl", required=True, type=pathlib.Path)
    p.add_argument("--scene", type=pathlib.Path, default=here.parent / "mjcf" / "g1_conveyor_scene.xml")
    p.add_argument("--hulls", type=int, default=64)
    p.add_argument("--threshold", type=float, default=0.03)
    p.add_argument("--preprocess-resolution", type=int, default=50)
    a = p.parse_args(argv)
    hv = decompose(a.stl, a.hulls, a.threshold, a.preprocess_resolution)
    bodies = rewrite(a.scene, hv)
    print(f"{len(hv)} hulls, {sum(len(v) for v in hv)} vertices, written to {bodies} panel bodies")
    return 0


if __name__ == "__main__":
    sys.exit(main())
