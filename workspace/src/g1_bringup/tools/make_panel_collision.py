#!/usr/bin/env python3
"""Generate the BSH panel's compound collision meshes in g1_conveyor_scene.xml.

MuJoCo collides a mesh as its single convex hull. BSH_panel.stl is a shell with two clips
hanging 31 mm below it near its front edge, at one end only, so its single hull has a sloped
underside running from the clip tips to the opposite end: dropped on a flat support it lands
on the clips and tips over, which is what kept it out of the pallet nest. This splits the
collision into three hulls -- the shell, and each clip on its own -- so the panel rests on its
real feet and the clips hang free, the way the real pallet carries it.

    make_panel_collision.py --stl /path/to/BSH_panel.stl     # ASCII or binary STL

It rewrites only the block between the BEGIN/END markers inside the scene's <asset>, as
inline-vertex meshes (MuJoCo builds each hull itself), so no extra mesh files have to be
copied anywhere. The visual mesh (`part_mesh`, the STL itself) is unchanged.

Vertices are written in the PANEL BODY frame: STL coordinates minus the scene's mesh refpos
(0, 0.001, -0.046), exactly as `part_mesh` places them. In that frame body +y points down in
the world (the scene's euler="-1.5708 1.57 0"), so the clips are the points far out along +y.
"""

import argparse
import pathlib
import re
import struct
import sys

import numpy as np
from scipy.spatial import ConvexHull

BEGIN = "<!-- BEGIN generated by tools/make_panel_collision.py -- do not edit by hand -->"
END = "<!-- END generated by tools/make_panel_collision.py -->"

REFPOS = np.array([0.0, 0.001, -0.046])  # must match <mesh name="part_mesh" refpos=...>
CLIP_BELOW = 0.015  # body +y beyond which a point is a clip, not shell (shell bottom is 0.0122)
CLIP_GAP = 0.02  # clips further apart than this along body x are separate hulls
VOXEL = 0.002  # shell hull decimation: one candidate point per 2 mm cell


def load_stl(path):
    data = path.read_bytes()
    if len(data) >= 84:
        count = struct.unpack("<I", data[80:84])[0]
        if 84 + 50 * count == len(data):
            rec = np.frombuffer(data[84:], dtype=np.dtype([("n", "<3f4"), ("v", "<9f4"), ("a", "<u2")]))
            return rec["v"].reshape(-1, 3).astype(np.float64)
    text = data.decode("ascii", errors="replace")
    pts = re.findall(r"vertex\s+(\S+)\s+(\S+)\s+(\S+)", text)
    if not pts:
        raise SystemExit(f"{path}: neither a binary nor an ASCII STL")
    return np.array(pts, dtype=np.float64)


def hull_vertices(points):
    return points[ConvexHull(points).vertices]


def decimate(points, cell):
    """Keep, per voxel, the point farthest from the centroid: the hull keeps its extremes to
    within one cell, with a fraction of the vertices."""
    centre = points.mean(axis=0)
    keys = np.floor(points / cell).astype(np.int64)
    far = np.linalg.norm(points - centre, axis=1)
    order = np.lexsort((-far, keys[:, 2], keys[:, 1], keys[:, 0]))
    k = keys[order]
    first = np.ones(len(k), dtype=bool)
    first[1:] = np.any(k[1:] != k[:-1], axis=1)
    return points[order[first]]


def mesh_line(name, verts):
    flat = " ".join((f"{v:.5f}".rstrip("0").rstrip(".") or "0") for v in verts.ravel())
    return f'    <mesh name="{name}" vertex="{flat}"/>'


def build(stl):
    pts = np.unique(load_stl(stl).round(6), axis=0) - REFPOS
    clip_mask = pts[:, 1] > CLIP_BELOW
    shell, clips = pts[~clip_mask], pts[clip_mask]
    if len(clips) == 0:
        raise SystemExit("no clip points found below the shell; is this the BSH panel?")

    # Split the clip points into separate clips along body x (world -y, across the belt).
    order = np.argsort(clips[:, 0])
    xs = clips[order, 0]
    cuts = np.where(np.diff(xs) > CLIP_GAP)[0] + 1
    groups = [clips[order[s:e]] for s, e in zip([0, *cuts], [*cuts, len(xs)])]

    shell_hull = hull_vertices(decimate(hull_vertices(shell), VOXEL))
    lines = [f"    {BEGIN}",
             "    <!-- Collision for the BSH panel, split so the clips do not tilt it: the shell, "
             f"and {len(groups)} clip(s), each its own convex hull, in the panel body frame. "
             "Regenerate with make_panel_collision.py --stl BSH_panel.stl. -->",
             mesh_line("part_col_shell", shell_hull)]
    for i, g in enumerate(groups, start=1):
        lines.append(mesh_line(f"part_col_clip_{i}", hull_vertices(g)))
    lines.append(f"    {END}")
    summary = (f"shell hull {len(shell_hull)} vertices (from {len(shell)} points), "
               f"{len(groups)} clips: " + ", ".join(
                   f"x {g[:,0].min()*1000:.0f}..{g[:,0].max()*1000:.0f} mm, {len(hull_vertices(g))} verts"
                   for g in groups))
    return "\n".join(lines) + "\n", summary


def main(argv=None):
    here = pathlib.Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--stl", required=True, type=pathlib.Path)
    parser.add_argument("--scene", type=pathlib.Path, default=here.parent / "mjcf" / "g1_conveyor_scene.xml")
    args = parser.parse_args(argv)

    block, summary = build(args.stl)
    text = args.scene.read_text()
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise SystemExit(f"{args.scene}: expected exactly one BEGIN marker followed by one END marker")
    line_start = text.rfind("\n", 0, text.index(BEGIN)) + 1
    line_end = text.find("\n", text.index(END))
    line_end = len(text) if line_end == -1 else line_end + 1
    args.scene.write_text(text[:line_start] + block + text[line_end:])
    print(f"wrote {args.scene}: {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
