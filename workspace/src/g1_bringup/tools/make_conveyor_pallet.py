#!/usr/bin/env python3
"""Generate the slotted pallet block in g1_conveyor_scene.xml.

The real line carries Mert's panels on a pallet: an aluminium plate riding the roller conveyor,
four panels face-up side by side across it, held at each end by white blocks. The panel
(BSH_panel.stl) has two clips hanging 31 mm below its shell near its front edge, so it cannot lie
on a flat plate: it rests on the feet at its two ends, and the clips hang free. Each nest here is
therefore two end cradles, one under each end of the panel:

  pad    under the panel's end, carrying its feet high enough that the clips clear the plate,
         stopping short of the clip that sits near one end;
  wall   outboard of the end, locating the panel across the belt;
  stops  posts in front of and behind the end, locating it along travel; shared between
         neighbouring nests, so nests sit one pitch apart with nothing else between them;
  base   a 3 mm floor slab under the cradle, so pad, wall and stops form one solid part (the
         same solid tools/export_conveyor_pallet_stl.py writes out as an STL).

Measured off BSH_panel.stl in the scene's orientation (euler="-1.5708 1.57 0", refpos
0 0.001 -0.046): half-extents 0.298 across the belt and 0.0683 along it; feet 12.25 mm below the
panel origin, at |y| 0.284..0.298; clips down to 43.45 mm below the origin at x +44.7..+52.0 mm,
y +115..+131 and +262..+271 mm. If the part changes, re-measure these (see make_panel_collision.py
for the frame) before trusting the nest.

It is a generator rather than hand-written XML because MJCF has no variables, and the one number
that has to be easy to change -- the clearance between panel and nest, until the customer's real
tolerance is known -- moves every wall and the pitch between nests. Rerun it after changing
anything here; it rewrites only the block between the BEGIN/END markers.

    make_conveyor_pallet.py --clearance-mm 2.0          # default scene path, 4 nests
    make_conveyor_pallet.py --clearance-mm 1.0 --nests 4 --load-x 0.40

Names the simulator's conveyor handler looks up (do not rename without changing it too):
  conveyor_pallet          the pallet body
  conveyor_pallet_slide    its slide joint, the only way it moves (no free joint: it cannot
                           yaw, tip or drift sideways, so its pose is always exactly known)
  conveyor_pallet_plate    the plate; its footprint is where the belt drag stays off
  conveyor_nest_<k>        box sites, one per nest, k = 1 at the downstream end; a panel whose
                           origin is inside one, at rest and untouched by the robot, fills it
  conveyor_load_station    world site the pallet indexes nests to

The plate takes the scene's tray_top_mat, so the pallet follows the scene's palette; the
cradles are white, like the real line's blocks.
"""

import argparse
import pathlib
import sys

BEGIN = "<!-- BEGIN generated by tools/make_conveyor_pallet.py -- do not edit by hand -->"
END = "<!-- END generated by tools/make_conveyor_pallet.py -->"

# The panel, measured (see the docstring). World-aligned, relative to the panel body origin.
PART_HALF_ACROSS = 0.298  # world y
PART_HALF_ALONG = 0.0683  # world x
FEET_BELOW = 0.01225  # lowest point of the shell, below the origin
CLIP_BELOW = 0.04345  # lowest point of the clips
CLIP_NEAREST_X = 0.0447  # closest a clip comes to the origin along +x

# The conveyor this sits on (g1_conveyor_scene.xml): belt box centred at y 0.60, top surface
# at z 0.75, running x -0.20 .. 1.30. The rails' inner faces are at y 0.27 / 0.93.
BELT_Y = 0.60
BELT_TOP = 0.75
BELT_X_MIN = -0.20
BELT_X_MAX = 1.30
RAIL_INNER_HALF = 0.33  # belt centre to rail inner face

# Pallet build. The plate floats 2 mm above the belt box so the two never touch: the pallet is
# carried by its slide joint, and a sliding contact against the belt would only add friction.
PLATE_GAP = 0.002
PLATE_HALF_T = 0.01
PLATE_MARGIN_X = 0.02  # plate beyond the first/last stop
PAD_HEIGHT = 0.040  # pad top above the plate: clips end up this minus 31.2 mm (8.8 mm) clear
PAD_INNER = 0.255  # pads start this far out from the panel centre (the feet are beyond 0.284)
PAD_BACK_X = -0.066  # pad extent along travel, relative to the nest centre ...
PAD_FRONT_X = CLIP_NEAREST_X - 0.008  # ... stopping 8 mm short of the clip near the +y end
WALL_HALF_T = 0.008  # end wall thickness (across the belt)
WALL_ABOVE = 0.030  # end wall top above the pad top
STOP_HALF_T = 0.005  # stop thickness (along travel)
STOP_ABOVE = 0.020  # stop top above the pad top
BASE_T = 0.003  # floor slab under each cradle, tying pad, wall and stops into one solid part
PALLET_MASS = 10.0
SITE_MARGIN = 0.003  # nest sites reach this far past the clearance, so a seated panel reads as inside
SITE_HALF_UP = 0.008  # and this far up/down from the seated height: resting, not hovering
END_MARGIN = 0.05  # how short of the belt's far end the pallet stops
WHITE = 'rgba="0.95 0.95 0.95 1"'


def num(v):
    text = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def box(name, size, pos, look):
    return (f'<geom name="{name}" group="2" type="box" size="{" ".join(num(s) for s in size)}" '
            f'pos="{" ".join(num(p) for p in pos)}" {look} contype="1" conaffinity="1"/>')


def pallet_geometry(clearance, nests):
    """Every solid of the pallet as boxes in the pallet frame (origin at the plate's centre, x
    along travel, z up), plus the derived dimensions. The single source for both the scene block
    (build) and the STL export (export_conveyor_pallet_stl.py), so the two cannot drift apart."""
    pitch = 2 * (PART_HALF_ALONG + clearance) + 2 * STOP_HALF_T
    wall_y = PART_HALF_ACROSS + clearance + WALL_HALF_T
    plate_half_x = nests * pitch / 2 + STOP_HALF_T + PLATE_MARGIN_X
    plate_half_y = wall_y + WALL_HALF_T
    plate_top = PLATE_HALF_T

    def nest_x(k):  # nest k (1-based) centre, k = 1 at the downstream end
        return ((nests + 1) / 2 - k) * pitch

    boxes = [("conveyor_pallet_plate", (plate_half_x, plate_half_y, PLATE_HALF_T), (0, 0, 0))]
    pad_half = ((PAD_FRONT_X - PAD_BACK_X) / 2, (PART_HALF_ACROSS - PAD_INNER) / 2, PAD_HEIGHT / 2)
    pad_cx = (PAD_FRONT_X + PAD_BACK_X) / 2
    pad_cy = (PART_HALF_ACROSS + PAD_INNER) / 2
    wall_h = PAD_HEIGHT + WALL_ABOVE
    stop_h = PAD_HEIGHT + STOP_ABOVE
    for k in range(1, nests + 1):
        cx = nest_x(k)
        for end, sign in (("a", -1), ("b", 1)):
            boxes.append((f"conveyor_nest_{k}_pad_{end}", pad_half,
                          (cx + pad_cx, sign * pad_cy, plate_top + PAD_HEIGHT / 2)))
            boxes.append((f"conveyor_nest_{k}_wall_{end}", (pitch / 2, WALL_HALF_T, wall_h / 2),
                          (cx, sign * wall_y, plate_top + wall_h / 2)))
    # Floor slab under each end region, the full pallet length: one strip per end that every
    # cradle stands on, so each cradle is a single connected solid.
    base_half = (nests * pitch / 2 + STOP_HALF_T, (wall_y + WALL_HALF_T - PAD_INNER) / 2, BASE_T / 2)
    base_cy = (wall_y + WALL_HALF_T + PAD_INNER) / 2
    for end, sign in (("a", -1), ("b", 1)):
        boxes.append((f"conveyor_pallet_base_{end}", base_half, (0, sign * base_cy, plate_top + BASE_T / 2)))
    # Stops at every nest boundary, in both end regions only: the middle of the panel stays
    # open, as on the real pallet, and nothing stands under the clips.
    stop_half_y = (PART_HALF_ACROSS + clearance - PAD_INNER) / 2
    stop_cy = (PART_HALF_ACROSS + clearance + PAD_INNER) / 2
    for r in range(nests + 1):
        rx = nest_x(1) + pitch / 2 - r * pitch
        for end, sign in (("a", -1), ("b", 1)):
            boxes.append((f"conveyor_pallet_stop_{r}_{end}", (STOP_HALF_T, stop_half_y, stop_h / 2),
                          (rx, sign * stop_cy, plate_top + stop_h / 2)))
    return {
        "pitch": pitch,
        "plate_half_x": plate_half_x,
        "plate_half_y": plate_half_y,
        "plate_top": plate_top,
        "nest_x": [nest_x(k) for k in range(1, nests + 1)],
        "seat_above_plate_top": PAD_HEIGHT + FEET_BELOW,  # panel origin height over the plate top
        "boxes": boxes,
    }


def build(clearance, nests, load_x):
    geo = pallet_geometry(clearance, nests)
    pitch, plate_half_x, plate_half_y = geo["pitch"], geo["plate_half_x"], geo["plate_half_y"]
    if plate_half_y > RAIL_INNER_HALF - 0.005:
        raise SystemExit(f"pallet half-width {plate_half_y:.4f} m does not clear the rails: reduce the clearance")

    body_z = BELT_TOP + PLATE_GAP + PLATE_HALF_T  # pallet origin = plate centre
    seat_z = body_z + geo["plate_top"] + geo["seat_above_plate_top"]  # world z of a seated panel
    clip_clear = PAD_HEIGHT + FEET_BELOW - CLIP_BELOW - BASE_T  # the near-end clip hangs over the base
    if clip_clear < 0.003:
        raise SystemExit("PAD_HEIGHT leaves the clips touching the cradle base")

    x0 = load_x - geo["nest_x"][0]  # pallet origin with nest 1 at the station, slide q = 0
    if x0 - plate_half_x < BELT_X_MIN:
        raise SystemExit(f"--load-x {load_x}: pallet would start off the belt's near end")
    q_max = (BELT_X_MAX - END_MARGIN - plate_half_x) - x0
    q_last = (nests - 1) * pitch
    if q_max < q_last:
        raise SystemExit("belt too short for this many nests at this load station")

    pad = "    "
    out = [
        f"{pad}{BEGIN}",
        f"{pad}<!-- Pallet after the real line: {nests} nests, clearance {clearance * 1000:.1f} mm "
        f"per side, pitch {pitch * 1000:.1f} mm. Each nest is two white end cradles carrying the "
        f"panel by its end feet, {PAD_HEIGHT * 1000:.0f} mm above the plate so its clips hang "
        f"{clip_clear * 1000:.1f} mm clear. Indexed by the conveyor handler: nest 1 starts at the "
        "load station; each time a panel settles there, untouched by the robot, the pallet "
        "advances one pitch; once the last nest is filled it runs to the belt's end and stops. "
        f"Regenerate with make_conveyor_pallet.py --clearance-mm {clearance * 1000:g} "
        f"--nests {nests} --load-x {load_x:g}. -->",
        f'{pad}<site name="conveyor_load_station" group="4" type="sphere" size="0.01" '
        f'pos="{num(load_x)} {num(BELT_Y)} {num(seat_z)}" rgba="0.1 0.6 1 0.6"/>',
        f'{pad}<body name="conveyor_pallet" pos="{num(x0)} {num(BELT_Y)} {num(body_z)}">',
        f'{pad}  <joint name="conveyor_pallet_slide" type="slide" axis="1 0 0" limited="true" '
        f'range="0 {num(q_max)}" damping="20"/>',
        f'{pad}  <inertial pos="0 0 0" mass="{num(PALLET_MASS)}" diaginertia="0.4 0.4 0.8"/>',
    ]
    for name, half, pos in geo["boxes"]:
        if name == "conveyor_pallet_plate":
            out.append(f'{pad}  <geom name="{name}" group="2" type="box" '
                       f'size="{" ".join(num(h) for h in half)}" pos="0 0 0" '
                       f'material="tray_top_mat" contype="1" conaffinity="1" friction="0.8 0.01 0.0001"/>')
        else:
            out.append(pad + "  " + box(name, half, pos, WHITE))
    for k, cx in enumerate(geo["nest_x"], start=1):
        out.append(
            f'{pad}  <site name="conveyor_nest_{k}" group="4" type="box" '
            f'size="{num(PART_HALF_ALONG + clearance + SITE_MARGIN)} '
            f'{num(PART_HALF_ACROSS + clearance + SITE_MARGIN)} {num(SITE_HALF_UP)}" '
            f'pos="{num(cx)} 0 {num(seat_z - body_z)}" rgba="0.2 0.9 0.3 0.25"/>'
        )
    out += [f"{pad}</body>", f"{pad}{END}"]

    summary = (
        f"{nests} nests, clearance {clearance * 1000:.1f} mm, pitch {pitch * 1000:.1f} mm, "
        f"pallet {2 * plate_half_x:.3f} x {2 * plate_half_y:.3f} m, seat z {seat_z:.4f}, "
        f"clips {clip_clear * 1000:.1f} mm clear, travel 0..{q_max:.3f} m "
        f"(last nest at the station at {q_last:.3f})"
    )
    return "\n".join(out) + "\n", summary


def main(argv=None):
    here = pathlib.Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--scene", type=pathlib.Path, default=here.parent / "mjcf" / "g1_conveyor_scene.xml")
    parser.add_argument("--clearance-mm", type=float, default=2.0,
                        help="gap between the panel and each nest wall, per side")
    parser.add_argument("--nests", type=int, default=4)
    parser.add_argument("--load-x", type=float, default=0.40,
                        help="world x of the load station, where every panel is placed")
    args = parser.parse_args(argv)
    if args.clearance_mm < 0 or args.nests < 1:
        raise SystemExit("--clearance-mm must be >= 0 and --nests >= 1")

    block, summary = build(args.clearance_mm / 1000.0, args.nests, args.load_x)
    text = args.scene.read_text()
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise SystemExit(f"{args.scene}: expected exactly one BEGIN marker followed by one END marker")
    # Replace whole lines, from the BEGIN marker's line through the END marker's line.
    line_start = text.rfind("\n", 0, text.index(BEGIN)) + 1
    line_end = text.find("\n", text.index(END))
    line_end = len(text) if line_end == -1 else line_end + 1
    args.scene.write_text(text[:line_start] + block + text[line_end:])
    print(f"wrote {args.scene}: {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
