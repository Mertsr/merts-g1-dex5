#!/usr/bin/env python3
"""Derive g1_29dof_no_hands.urdf from the vendored Unitree description.

The vendored URDF ends each arm in a Dex3-1 hand: a palm and seven finger links per side. This
robot carries Inspire RH56E2 hands instead, so those links have to go, and xacro can add to a
URDF but cannot remove from one. The vendored file stays untouched, so it remains diffable
against Unitree's, and this script derives the hand-less one from it.

What survives of each hand is `{side}_hand_palm_link` and the fixed joint that places it on
the wrist, reduced to an empty frame. It is still the arm's tip in MoveIt and the mount for the
new hand, so g1_moveit_config and g1_manipulation keep the names they already use.

    make_no_hands_urdf.py            rewrite the checked-in file
    make_no_hands_urdf.py --check    exit 1 if the checked-in file has drifted (used by the tests)
"""

import argparse
import pathlib
import re
import sys

_URDF_DIR = pathlib.Path(__file__).resolve().parent.parent / "urdf"
SOURCE = _URDF_DIR / "g1_29dof_with_hand_rev_1_0.urdf"
TARGET = _URDF_DIR / "g1_29dof_no_hands.urdf"

# The seven Dex3 finger joints and their links. The palm is handled separately.
_DEX3_PARTS = re.compile(r"^(left|right)_hand_(thumb|middle|index)_[0-2]_(joint|link)$")
_PALM_LINK = re.compile(r"^(left|right)_hand_palm_link$")

_BLOCK_OPEN = re.compile(r'^  <(joint|link) name="([^"]+)"')
_BLOCK_CLOSE = {"joint": "  </joint>", "link": "  </link>"}

_NOTE = (
    "  <!-- GENERATED by g1_description/scripts/make_no_hands_urdf.py from\r\n"
    "       g1_29dof_with_hand_rev_1_0.urdf. Do not edit; edit the script. The Dex3-1 palm and\r\n"
    "       finger links are gone, and each palm link is an empty frame that the RH56E2 hand is\r\n"
    "       mounted on. See g1_description/README.md. -->\r\n"
)


def _blocks(lines):
    """Yield (kind, name, lines) for each two-space-indented joint or link, else (None, None, [line])."""
    i = 0
    while i < len(lines):
        match = _BLOCK_OPEN.match(lines[i])
        if match is None:
            yield None, None, [lines[i]]
            i += 1
            continue
        kind, name = match.groups()
        # A self-closing element is one line.
        if lines[i].rstrip().endswith("/>"):
            yield kind, name, [lines[i]]
            i += 1
            continue
        j = i
        while lines[j].rstrip("\r\n") != _BLOCK_CLOSE[kind]:
            j += 1
        yield kind, name, lines[i : j + 1]
        i = j + 1


def derive(text):
    lines = text.splitlines(keepends=True)
    out = []
    removed = {"left": 0, "right": 0}
    emptied = 0
    for kind, name, block in _blocks(lines):
        if kind is not None and _DEX3_PARTS.match(name):
            removed[name.split("_", 1)[0]] += 1
            continue
        if kind == "link" and _PALM_LINK.match(name):
            out.append(f'  <link name="{name}"/>\r\n')
            emptied += 1
            continue
        out.extend(block)

    # 7 joints + 7 links per hand. Anything else means the vendored file changed shape.
    if removed != {"left": 14, "right": 14} or emptied != 2:
        raise SystemExit(f"unexpected vendored layout: removed {removed}, emptied {emptied}")

    # The note goes straight after the <robot> tag, whose line ends in CRLF.
    first = out[0]
    assert first.startswith("<robot "), first
    return "".join([first, _NOTE, *out[1:]])


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="verify instead of writing")
    args = parser.parse_args(argv)

    derived = derive(SOURCE.read_bytes().decode("utf-8"))
    if args.check:
        current = TARGET.read_bytes().decode("utf-8") if TARGET.exists() else ""
        if current != derived:
            print(f"{TARGET.name} is out of date; run {pathlib.Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    TARGET.write_bytes(derived.encode("utf-8"))
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
